import math
import os

# constants representing the species and counts
SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"

NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151

species_names = [
    SP_CHINSTRAP,
    SP_GENTOO,
    SP_ADELIE
]

species_counts = [
    NUM_CHINSTRAP,
    NUM_GENTOO,
    NUM_ADELIE
]


# locate the Palmer Penguins CSV file
def get_csv_path():
    possible_paths = [
        "PalmerPenguins.csv",
        "/content/PalmerPenguins.csv"
    ]

    for path in possible_paths:
        if os.path.exists(path):
            return path

    raise FileNotFoundError(
        "PalmerPenguins.csv was not found. "
        "Upload it to the Colab Files panel."
    )


# read a specific penguin observation from the CSV file
def read_penguin_row(row_number):
    csv_path = get_csv_path()

    with open(csv_path, "r") as penguin_file:
        penguin_file.readline()

        current_row = 1

        for line in penguin_file:
            if current_row == row_number:
                values = line.strip().split(",")

                return {
                    "sample_number": values[0],
                    "species": values[1],
                    "culmen_length": values[2]
                }

            current_row += 1

    return None


# calculate a species percentage
def calculate_percentage(count, total):
    return count / total * 100


# classify a species by percentage
def classify_species(percent):
    if percent < 25:
        return "small"
    elif percent < 40:
        return "medium"
    else:
        return "large"


# display one observation from the CSV file
def display_penguin(row_number):
    penguin = read_penguin_row(row_number)

    if penguin is not None:
        print()
        print("Sample Penguin Observation:")
        print(f"Sample Number: {penguin['sample_number']}")
        print(f"Species: {penguin['species']}")
        print(
            f"Culmen Length: "
            f"{penguin['culmen_length']} mm"
        )


def main():
    total_species = len(species_names)
    total_penguins = sum(species_counts)

    average_penguins = total_penguins / total_species
    average_rounded = math.ceil(average_penguins)

    species_percentages = []

    for count in species_counts:
        percent = calculate_percentage(
            count,
            total_penguins
        )
        species_percentages.append(percent)

    largest_count = max(species_counts)
    smallest_count = min(species_counts)

    largest_index = species_counts.index(largest_count)
    smallest_index = species_counts.index(smallest_count)

    largest_species = species_names[largest_index]
    smallest_species = species_names[smallest_index]

    print("Introducing the Palmer Penguins:")
    print(f" {species_names[0]}!")
    print(f" {species_names[1]}!")
    print("and last but not least...")
    print(f" {species_names[2]}!")

    print(
        f"There are a total of {total_species} "
        f"penguin species in this dataset."
    )
    print(
        f"There are a total of {total_penguins} "
        f"penguins in the dataset."
    )
    print(
        f"The average number of penguins per species "
        f"is {average_penguins:.1f}."
    )
    print(
        f"The average rounded up is "
        f"{average_rounded} penguins."
    )

    for index, species in enumerate(species_names):
        print(
            f"{species}: {species_counts[index]} "
            f"({species_percentages[index]:.2f}%)"
        )

    print(
        f"The species with the most observations is "
        f"{largest_species} with {largest_count} penguins."
    )
    print(
        f"The species with the fewest observations is "
        f"{smallest_species} with {smallest_count} penguins."
    )

    # read and display two observations from the CSV
    display_penguin(1)
    display_penguin(342)

    valid_selections = 0

    print()
    print("Explore a species:")

    species_choice = input(
        "Enter Chinstrap, Gentoo, Adelie, or Done: "
    )

    while species_choice != "Done":

        if species_choice not in species_names:
            print(
                f"{species_choice} is not one of the species "
                f"in this dataset."
            )

        else:
            selected_index = species_names.index(
                species_choice
            )

            selected_species = species_names[
                selected_index
            ]
            selected_count = species_counts[
                selected_index
            ]
            selected_percent = species_percentages[
                selected_index
            ]

            size_category = classify_species(
                selected_percent
            )

            if selected_species == largest_species:
                position_description = "largest"
            elif selected_species == smallest_species:
                position_description = "smallest"
            else:
                position_description = "middle-sized"

            if selected_count > average_penguins:
                average_position = "above"
            else:
                average_position = "below"

            valid_selections += 1

            print(
                f"{selected_species} has {selected_count} "
                f"observations, representing "
                f"{selected_percent:.2f}% of the dataset."
            )
            print(
                f"{selected_species} is classified as a "
                f"{size_category} species group."
            )
            print(
                f"{selected_species} is the "
                f"{position_description} species group."
            )
            print(
                f"Its observation count is "
                f"{average_position} the dataset average "
                f"of {average_penguins:.1f}."
            )

        species_choice = input(
            "Enter Chinstrap, Gentoo, Adelie, or Done: "
        )

    print(
        f"You explored {valid_selections} valid species."
    )
    print("Exploration complete.")


main()